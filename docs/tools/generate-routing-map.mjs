// Generate the routing mind map from the data that already decides routing.
//
// Nothing here is invented: the skill rows come from the corpus that the routing suite scores,
// the tool rows from the registered definitions, and the diagram families from the engine
// table. The map is therefore a *view* of the routing contract - if the corpus changes, the map
// changes with it.
//
// Usage: node docs/tools/generate-routing-map.mjs        (prints)
//        node docs/tools/generate-routing-map.mjs --write (writes docs/routing-map.md)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const repoRoot = fileURLToPath(new URL('../../', import.meta.url))
const skillsRoot = join(repoRoot, 'skills')

/** dsh-tool-skill: DEFAULT_CATALOG_DESCRIPTION_MAX_LENGTH. */
const SKILL_BUDGET = 500

function frontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)
  if (match === null) return {}
  const fields = {}
  for (const line of match[1].split(/\r?\n/)) {
    const pair = /^([A-Za-z-]+):\s*"?(.*?)"?$/.exec(line)
    if (pair !== null) fields[pair[1]] = pair[2]
  }
  return fields
}

// ------------------------------------------------------------------ the inputs --

const corpus = JSON.parse(readFileSync(join(repoRoot, 'tests/skill-routing/corpus.json'), 'utf8'))

const skills = []
for (const name of readdirSync(skillsRoot, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name)) {
  const file = join(skillsRoot, name, 'SKILL.md')
  if (!existsSync(file)) continue
  const fields = frontmatter(readFileSync(file, 'utf8'))
  const description = fields.description ?? ''
  const visible = description.length <= SKILL_BUDGET ? description : description.slice(0, SKILL_BUDGET - 3) + '...'
  // What each skill owns, from the corpus: the utterances it answers, and where its near misses go.
  const own = corpus.cases.filter((entry) => entry.skill === fields.name)
  const destinations = new Map()
  for (const entry of own) {
    for (const near of entry.nearMisses) destinations.set(near.expected, (destinations.get(near.expected) ?? 0) + 1)
  }
  skills.push({
    name: fields.name ?? name,
    visible,
    length: description.length,
    triggers: own.flatMap((entry) => entry.triggers.map((trigger) => trigger.utterance)),
    sends: [...destinations.entries()].sort((left, right) => right[1] - left[1]),
  })
}

const entry = readFileSync(join(repoRoot, 'src/index.ts'), 'utf8')
const modules = [...new Set([...entry.matchAll(/from '\.\/([a-z-]+)\.js'/g)].map((match) => match[1]).filter((name) => name === 'tool' || name.endsWith('-tool')))]
const tools = []
for (const module of modules) {
  const built = await import('file:///' + join(repoRoot, 'lib', module + '.js').replaceAll('\\', '/'))
  for (const value of Object.values(built)) {
    if (value !== null && typeof value === 'object' && typeof value.name === 'string' && typeof value.description === 'string' && value.parameters !== undefined) {
      tools.push({ name: value.name, description: value.description, first: (value.description.split(/(?<=\.)\s/)[0] ?? '').slice(0, 150) })
    }
  }
}
tools.sort((left, right) => left.name.localeCompare(right.name))

const { UML_FAMILIES } = await import('file:///' + join(repoRoot, 'lib/uml-syntax.js').replaceAll('\\', '/'))

/** Which skill owns which tools. Declared here because it is a routing decision, not derivable. */
const TOOL_OWNER = {
  'model-everything': ['model_verify', 'model_compose_verify', 'model_export', 'report_diff'],
  'model-everything-uml': ['uml_render', 'uml_parse', 'uml_review', 'uml_explain_labels'],
  'model-everything-structure': ['uml_structure_verify'],
  'model-everything-datamodel': ['model_datamodel_verify'],
  'model-everything-concurrency': ['model_concurrency_scan'],
  'model-everything-design': ['model_design_review'],
}

const quote = (text) => '"' + text.replaceAll('"', "'").replaceAll('\n', ' ') + '"'

// ------------------------------------------------------------------- the map --

const lines = []
lines.push('# Routing map')
lines.push('')
lines.push('Generated by `docs/tools/generate-routing-map.mjs` from the routing corpus, the registered')
lines.push('tool definitions and the family table. Do not edit by hand: change the data and regenerate,')
lines.push('or the map starts describing a routing contract that no longer exists.')
lines.push('')
lines.push('## The decision the model makes, and what it can see')
lines.push('')
lines.push('```mermaid')
lines.push('mindmap')
lines.push('  root(("a question arrives"))')
lines.push('    gate1["GATE 1 - which skill answers this?"]')
lines.push('      sees1["sees: 6 skill rows"]')
lines.push('      budget["each row = description only, cut at 500 chars"]')
lines.push('      blind1["cannot see: whenToUse, the body, the tool table"]')
lines.push('    gate2["GATE 2 - which tool does it?"]')
lines.push('      sees2["sees: every registered tool schema"]')
lines.push('      whole["description and parameters come through whole"]')
lines.push('      blind2["cannot see: why the description says what it says"]')
lines.push('    gate3["GATE 3 - what do I put in the model?"]')
lines.push('      schema["sees: the parameter schema, field by field"]')
lines.push('      closed["closed schema: an unknown key is refused, not ignored"]')
lines.push('      story["the body it just loaded is where the field semantics live"]')
for (const skill of skills) {
  const label = skill.name.replace('model-everything', 'me')
  lines.push('    ' + label + '["' + label + ' - ' + String(skill.triggers.length) + ' corpus trigger(s)"]')
  lines.push('      len["row: ' + String(skill.length) + ' of ' + String(SKILL_BUDGET) + ' chars"]')
  for (const tool of TOOL_OWNER[skill.name] ?? []) lines.push('      ' + tool + '["tool: ' + tool + '"]')
  for (const [destination, count] of skill.sends) lines.push('      ' + destination.replaceAll('-', '_') + '["near miss x' + String(count) + ' -> ' + destination.replace('model-everything', 'me') + '"]')
}
lines.push('```')
lines.push('')
lines.push('## Who owns which question (from the corpus)')
lines.push('')
lines.push('| Skill | Row length | Owns these questions | Sends the near miss to |')
lines.push('|---|---|---|---|')
for (const skill of skills) {
  const owns = skill.triggers.slice(0, 3).map((trigger) => '"' + trigger + '"').join('<br>')
  const sends = skill.sends.map(([destination, count]) => destination.replace('model-everything', 'me') + ' x' + String(count)).join(', ')
  lines.push('| `' + skill.name + '` | ' + String(skill.length) + '/' + String(SKILL_BUDGET) + ' | ' + owns + ' | ' + sends + ' |')
}
lines.push('')
lines.push('## The overlap that has to be resolved in words')
lines.push('')
lines.push('Every pair below is a boundary the corpus already tests. The map names the deciding')
lines.push('question for each; that question is what the two descriptions have to make visible, and what')
lines.push('no amount of prose elsewhere can substitute for, because the model reads the rows and')
lines.push('nothing else at that moment.')
lines.push('')
lines.push('| Boundary | The deciding question |')
lines.push('|---|---|')
lines.push('| `me-structure` vs `me-design` | Is the input a **drawing** of an architecture (then structure) or a **design with its own declarations** to be held to (then design)? |')
lines.push('| `me-uml` vs `me-structure` | Is the question about the **diagram as a drawing** (round trip, modelling quality) or about the **graph it denotes** (dependencies, layers)? |')
lines.push('| `me` vs all specialised | Is there a stated claim to **verify against code** (then `me`), or a domain artefact to review (then the domain skill)? |')
lines.push('| `me-datamodel` vs `me-structure` | Are the nodes **tables and fields**, or **modules and packages**? |')
lines.push('| `me-concurrency` vs `me` | Does the claim use **concurrency vocabulary** (thread-safe, lock-free, ISR), or is it a sequential behavioural claim? |')
lines.push('')
lines.push('## What each description has to carry, given the gate it is read at')
lines.push('')
lines.push('| Text | Read at | Must contain | Must not contain |')
lines.push('|---|---|---|---|')
lines.push('| Skill `description` | gate 1, truncated at 500, competing with 5 siblings | the trigger in the first sentence; the sibling that owns the adjacent case | anything whose meaning needs the body; any number that a release changes |')
lines.push('| Tool `description` | gate 2, whole, competing with 12 siblings | what question it answers; when **not** to call it, or which sibling to call instead | a restatement of the tool name; claims the schema does not support |')
lines.push('| Tool parameter `description` | gate 3, whole, inside one field at a time | the form the value takes, and the default | the family doctrine, which belongs in the body |')
lines.push('| Skill body | after loading, unbounded | the decision rules, the codes, the limits | a second copy of the catalog row |')
lines.push('')
lines.push('## The tools, by owner')
lines.push('')
lines.push('| Tool | Owned by skill | First sentence (what the model reads first) |')
lines.push('|---|---|---|')
for (const tool of tools) {
  const owner = Object.entries(TOOL_OWNER).find(([, owned]) => owned.includes(tool.name))?.[0] ?? '(none)'
  lines.push('| `' + tool.name + '` | `' + owner + '` | ' + quote(tool.first) + ' |')
}
lines.push('')
lines.push('## Diagram families: where a UML question lands')
lines.push('')
lines.push('A family question is gate 1 (`me-uml`), then gate 2 by action: drawing is `uml_render`,')
lines.push('reading a hand-drawn diagram is `uml_parse`, judging the modelling is `uml_review`, and the')
lines.push('label contract is `uml_explain_labels`. The engine table decides what each notation can say,')
lines.push('so the tool descriptions do not repeat it.')
lines.push('')
lines.push('| Family | Notation that draws it | Readable back |')
lines.push('|---|---|---|')
for (const family of UML_FAMILIES) {
  const notation = family.machine ? 'mermaid' : (family.notation ?? (family.plantuml !== 'none' ? 'plantuml' : 'mermaid'))
  lines.push('| `' + family.id + '` | ' + notation + ' | ' + (family.machine ? 'machine path' : family.parseable ? (family.parseThroughApproximation === true ? 'approximate view' : 'yes') : 'refused by design') + ' |')
}
lines.push('')


// The map is read by a renderer, so a malformed node is a broken deliverable rather than a
// cosmetic problem. Refuse to emit one.
const mermaid = lines.slice(lines.indexOf('```mermaid') + 1, lines.lastIndexOf('```'))
const nodeLine = /^[A-Za-z0-9_-]+(\[".*"\]|\(\(".*"\)\))$/
const malformed = mermaid.filter((line) => line.trim() !== '' && line.trim() !== 'mindmap' && !nodeLine.test(line.trim()))
if (malformed.length > 0) throw new Error('malformed mermaid node(s): ' + malformed.slice(0, 3).join(' | '))
const text = lines.join('\n')
if (process.argv.includes('--write')) {
  writeFileSync(join(repoRoot, 'docs/routing-map.md'), text)
  console.log('wrote docs/routing-map.md (' + String(text.length) + ' chars)')
} else {
  console.log(text)
}
