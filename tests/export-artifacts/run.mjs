// An exported artifact has to be readable by the tool it is for, and it has to keep user text out of the syntax.
//
// Two failures matter here. A hostile identifier - a quote, an angle bracket, an ampersand - that reaches the output unescaped produces a file
// the external tool cannot parse, which is worse than refusing: the reader believes they have a model. And an artifact without its tool's skeleton
// is a file that will be rejected at import with no explanation from this side.
import { exportModel } from '../../lib/exporters.js'

let failures = 0
function test(name, body) {
  try {
    body()
    console.log('PASS', name)
  } catch (error) {
    failures += 1
    console.log('FAIL', name, '-', error instanceof Error ? error.message : String(error))
  }
}

const FORMATS = ['uppaal', 'tla', 'prism', 'spin']
const MODEL = {
  schemaVersion: 1, init: 'i',
  states: [{ id: 'i' }, { id: 'd', terminal: true }],
  transitions: [{ from: 'i', event: 'go', to: 'd' }, { from: 'd', event: 'back', to: 'i' }],
}
const HOSTILE_ID = 'a<b&c>d"e'
const HOSTILE = {
  schemaVersion: 1, init: HOSTILE_ID,
  states: [{ id: HOSTILE_ID }, { id: 'z', terminal: true }],
  transitions: [{ from: HOSTILE_ID, event: 'go<x>', to: 'z' }],
}

const textOf = (model, format) => String(exportModel(model, format).primary ?? '')

test('a hostile identifier never reaches an artifact raw', () => {
  for (const format of FORMATS) {
    const text = textOf(HOSTILE, format)
    if (text.includes(HOSTILE_ID)) throw new Error(format + ' carries the identifier verbatim')
    if (text.includes('<b&c>')) throw new Error(format + ' carries the raw angle brackets')
  }
})

test('two identifiers that sanitise alike are told apart', () => {
  // Without this, two states become one name and the artifact silently describes a different machine.
  const collide = {
    schemaVersion: 1, init: 'a<b',
    states: [{ id: 'a<b' }, { id: 'a>b', terminal: true }],
    transitions: [{ from: 'a<b', event: 'go', to: 'a>b' }],
  }
  const names = [...textOf(collide, 'uppaal').matchAll(/<name[^>]*>([^<]*)<\/name>/g)].map((match) => match[1])
  const locationNames = names.filter((name) => name !== 'ModelEverything')
  if (locationNames.length !== 2) throw new Error('expected two locations, saw ' + String(locationNames.length))
  if (locationNames[0] === locationNames[1]) throw new Error('both states are named ' + String(locationNames[0]))
})

test('each artifact carries the skeleton its tool needs', () => {
  const uppaal = textOf(MODEL, 'uppaal')
  if (!uppaal.startsWith('<?xml')) throw new Error('UPPAAL: no XML declaration')
  if (!uppaal.includes('<nta>') || !uppaal.includes('</nta>')) throw new Error('UPPAAL: no nta element')
  const tla = textOf(MODEL, 'tla')
  if (!/^---- MODULE \w+ ----/m.test(tla)) throw new Error('TLA+: no MODULE header')
  if (!/^====+$/m.test(tla)) throw new Error('TLA+: no module terminator')
  const prism = textOf(MODEL, 'prism')
  if (!/^\s*(dtmc|mdp)\s*$/m.test(prism)) throw new Error('PRISM: no model type line')
  if (!/^\s*module\s+\w+/m.test(prism)) throw new Error('PRISM: no module')
  const spin = textOf(MODEL, 'spin')
  if (!/proctype\s+\w+/.test(spin)) throw new Error('SPIN: no proctype')
})

test('every format names itself, so a file is identifiable after it leaves', () => {
  for (const format of FORMATS) {
    const text = textOf(MODEL, format)
    if (!/generated by this plugin/i.test(text)) throw new Error(format + ': no provenance line')
  }
})

if (failures > 0) {
  console.log('export-artifacts tests failed:', failures)
  process.exit(1)
}
console.log('all export-artifacts tests passed')