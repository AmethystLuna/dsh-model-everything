// The client bundle: the one file the page's loader reads.
//
// A registration-less `lib/client.js` is a real failure that reads as "entry did not activate" - the app says one entry did not load and nothing in
// the plugin says why. So the bundle is checked for the wrapper it must carry, for the package id it must register, for React coming from the page
// rather than from a second copy, and for being the same bytes when the same source is built again.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

let failures = 0
function test(name, body) {
  try {
    body()
    console.log('PASS', name)
  } catch (error) {
    failures += 1
    console.log('FAIL', name, '-', error instanceof Error ? error.message : String(error))
  }
}

const repo = new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const bundlePath = join(repo, 'lib', 'client.js')
const pkg = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8'))
const bundle = readFileSync(bundlePath, 'utf8')

test('the bundle is a generated file and says so', () => {
  if (!bundle.startsWith('// Generated by scripts/build-client.mjs')) throw new Error('the first line is not the generator banner')
})

test('the bundle registers under the package name the manifest declares', () => {
  if (!bundle.includes('__ModuleLoader__.load')) throw new Error('no loader call: the entry would not activate')
  const id = /id:\s*["']([^"']+)["']/.exec(bundle)?.[1]
  if (id !== pkg.name) throw new Error('registers as ' + String(id) + ', manifest says ' + String(pkg.name))
})

test('React comes from the page, not from a second copy in the bundle', () => {
  // The loader supplies React; bundling it breaks hooks across the boundary and is a defect the size would never show.
  // The page hands `require` to the factory, and the bundle calls it for react: `hostRequire("react")`.
  // The page hands the factory its require, and the bundle calls that for react. What matters is that the id is asked for rather than bundled,
  // and that no react implementation came along with it.
  if (!/\(\s*["']react["']\s*\)/.test(bundle)) throw new Error('the bundle never asks for react')
  if (/react-dom\/client/.test(bundle)) throw new Error('the bundle carries a react-dom implementation')
})

test('building the same source twice produces the same bytes', () => {
  // A bundle that changed between two builds makes every later `git diff` a question, and a release impossible to reproduce.
  const digest = () => createHash('sha256').update(readFileSync(bundlePath)).digest('hex')
  const build = () => execFileSync(process.execPath, [join(repo, 'scripts', 'build-client.mjs')], { cwd: repo, stdio: 'ignore' })
  build()
  const first = digest()
  build()
  const second = digest()
  if (first !== second) throw new Error('two builds of one source differ')
  if (readFileSync(bundlePath, 'utf8') !== bundle) throw new Error('the rebuilt bundle differs from the committed one')
})

if (failures > 0) {
  console.log('client-bundle tests failed:', failures)
  process.exit(1)
}
console.log('all client-bundle tests passed')