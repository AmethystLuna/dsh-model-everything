// The Client half of this plugin, built to the one format the page's module loader accepts.
//
// The loader hands a factory a `require` for baseline modules only, so nothing here may depend on a
// relative import surviving into the browser: everything `src/client.ts` imports is bundled into a single
// file. React is the one exception, because the loader supplies it and bundling a second copy is a defect.
//
// The wrapper below is the loader contract itself, written once, here, rather than by hand in the output.
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'

const PACKAGE = 'dsh-model-everything'
const OUT = 'client.js'

const result = await build({
  entryPoints: ['src/client.ts'],
  bundle: true,
  // CommonJS, because the loader hands the factory `require` for baseline modules: the compiled file is
  // the factory body, so its `require('react')` resolves to that parameter rather than to a bundler shim.
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  // React comes from the page. Bundling it would ship a second copy and break hooks across the boundary.
  external: ['react'],
  write: false,
  logLevel: 'warning',
})

const code = result.outputFiles?.[0]?.text ?? ''
if (code === '') {
  console.error('build:client produced nothing')
  process.exit(1)
}

// `iife` with an external `react` leaves a bare `require('react')` in the output, which only exists inside
// the loader's factory. So the bundle is wrapped as that factory rather than executed at load time.
const wrapped =
  '// Generated by scripts/build-client.mjs - do not edit. Source: src/client.ts and src/render/*.ts.\n' +
  'window.__ModuleLoader__.load({\n' +
  '  id: ' + JSON.stringify(PACKAGE) + ',\n' +
  '  factory(require) {\n' +
  '    const module = { exports: {} };\n' +
  '    const exports = module.exports;\n' +
  code.replace(/^/gm, '    ') +
  '\n    return module.exports.default ?? module.exports;\n' +
  '  },\n' +
  '});\n'

writeFileSync(OUT, wrapped, 'utf8')
console.log('written: ' + OUT + ' (' + String(wrapped.length) + ' chars)')
