// The Client half of this plugin, built to the one format the page's module loader accepts.
//
// The loader serves a package's built client bundle from `lib/client.js` and hands its factory a `require`
// for baseline modules only, so nothing here may depend on a relative import surviving into the browser:
// everything `src/client.ts` imports is bundled into a single file. React is the one exception, because the
// loader supplies it and bundling a second copy is a defect.
//
// `tsc` also compiles `src/client.ts` to `lib/client.js` on its way through `npm run build`; this script
// runs after it and replaces that module with the wrapped bundle. One path, one file, no second candidate
// for the loader to pick up - a registration-less `lib/client.js` is a real failure that reads as
// "entry did not activate".
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'

const PACKAGE = 'dsh-model-everything'
const OUT = 'lib/client.js'

const result = await build({
  entryPoints: ['src/client.ts'],
  bundle: true,
  // CommonJS, because the loader hands the factory `require` for baseline modules: the compiled file is
  // the factory body, so its `require('react')` resolves to that parameter rather than to a bundler shim.
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  // React comes from the page. Bundling it would ship a second copy and break hooks across the boundary.
  external: ['react'],
  write: false,
  logLevel: 'warning',
})

const code = result.outputFiles?.[0]?.text ?? ''
if (code === '') {
  console.error('build:client produced nothing')
  process.exit(1)
}
if (/^\s*export\s/m.test(code)) {
  console.error('build:client produced an ES module export, which the loader cannot execute as a factory')
  process.exit(1)
}

// The loader's own factory must RETURN THE PLUGIN, and our source exports a function that builds it. So the
// wrapper hands that builder the loader's `require` and returns its result: returning the builder itself
// gives the loader a function where it expects `{ inject, apply }`, which fails the row with the single
// word `failed` and nothing else.
const wrapped =
  '// Generated by scripts/build-client.mjs - do not edit. Source: src/client.ts and src/render/*.ts.\n' +
  'window.__ModuleLoader__.load({\n' +
  '  id: ' + JSON.stringify(PACKAGE) + ',\n' +
  '  factory(require) {\n' +
  '    const module = { exports: {} };\n' +
  '    const exports = module.exports;\n' +
  code.replace(/^/gm, '    ') +
  '\n    const create = module.exports.default ?? module.exports;\n' +
  '    return create(require);\n' +
  '  },\n' +
  '});\n'

writeFileSync(OUT, wrapped, 'utf8')
console.log('written: ' + OUT + ' (' + String(wrapped.length) + ' chars)')
